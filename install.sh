#!/usr/bin/env bash
# Install Mess Ledger for the current user. No root, no system packages.
#
#   ./install.sh              install and launch
#   ./install.sh --no-launch  install only
#   ./install.sh --uninstall  remove it again
#   ./install.sh --autostart  open it at every login
#
# Everything lands under ~/.local so nothing outside your home is touched.
set -euo pipefail

SRC="$(cd "$(dirname "$0")" && pwd)"
PREFIX="${HOME}/.local"
APPDIR="$PREFIX/share/mess-ledger"
BINDIR="$PREFIX/bin"
LAUNCHER="$BINDIR/mess-ledger"
FONTDIR=""
DESKTOP_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
DESKTOP_FILE="$DESKTOP_DIR/mess-ledger.desktop"
AUTOSTART_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/autostart"
LAUNCH=1
MODE=install
AUTOSTART=0

case "${1:-}" in
  --no-launch) LAUNCH=0 ;;
  --autostart) AUTOSTART=1 ;;
  --no-autostart) AUTOSTART=0 ;;
  --uninstall) MODE=uninstall ;;
  -h|--help) sed -n '2,9p' "$0" | sed 's/^# //'; exit 0 ;;
  "") ;;
  *) echo "unknown option: $1" >&2; exit 2 ;;
esac

say() { printf '  %s\n' "$*"; }
die() { printf '\nerror: %s\n' "$*" >&2; exit 1; }

uninstall() {
  say "removing $LAUNCHER"
  rm -f "$LAUNCHER" "$DESKTOP_FILE" "$AUTOSTART_DIR/mess-ledger.desktop"
  say "removing $APPDIR"
  rm -rf "$APPDIR"
  if [ -n "$FONTDIR" ]; then
    say "removing bundled fonts"
    for f in Caveat DMMono Outfit PlayfairDisplay; do
      rm -f "$FONTDIR"/*"$f"*.ttf 2>/dev/null || true
    done
    command -v fc-cache >/dev/null && fc-cache -f "$FONTDIR" >/dev/null 2>&1 || true
  fi
  cat <<'EOF'

  Your meals are untouched. They live in:
    ~/.local/share/bhu_meal_tracker/history.json
    ~/.config/bhu_meal_tracker/config.ini
EOF
}

[ "$MODE" = uninstall ] && { uninstall; exit 0; }

# ---------------------------------------------------------------- checks
printf '\nMess Ledger - installing for %s\n\n' "$USER"

command -v python3 >/dev/null || die "python3 not found. Install Python 3.9 or newer."
PYV=$(python3 -c 'import sys; print("%d.%d" % sys.version_info[:2])')
python3 - <<'PY' || die "Python 3.9+ required (found $PYV)."
import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)
PY
say "python $PYV"

if ! python3 -c "import tkinter" >/dev/null 2>&1; then
  die "tkinter missing. On Debian/Ubuntu: sudo apt install python3-tk"
fi
say "tkinter present"

HAVE_PIL=1
python3 -c "import PIL" >/dev/null 2>&1 || HAVE_PIL=0
if [ "$HAVE_PIL" = 1 ]; then
  say "pillow present (photographs, doodles and the paper grain)"
else
  say "pillow NOT installed - the app runs, but falls back to plain paper"
  say "  install it with:  python3 -m pip install --user pillow"
fi

# ---------------------------------------------------------------- copy
mkdir -p "$APPDIR" "$BINDIR" "$DESKTOP_DIR"
for f in "$SRC"/*.py "$SRC"/art "$SRC"/icons "$SRC"/web "$SRC"/fonts; do
  [ -e "$f" ] || continue
  rm -rf "${APPDIR:?}/$(basename "$f")"
  cp -r "$f" "$APPDIR/"
done
cp "$SRC/README.md" "$APPDIR/" 2>/dev/null || true
say "app files -> $APPDIR"

# ---------------------------------------------------------------- fonts
case "$(uname -s)" in
  Darwin) FONTDIR="$HOME/Library/Fonts" ;;
  MINGW*|MSYS*|CYGWIN*) FONTDIR="${LOCALAPPDATA:-$HOME/AppData/Local}/Microsoft/Windows/Fonts" ;;
  *) FONTDIR="${XDG_DATA_HOME:-$HOME/.local/share}/fonts/meal-tracker" ;;
esac
if [ -d "$SRC/fonts" ]; then
  mkdir -p "$FONTDIR"
  cp "$SRC"/fonts/*.ttf "$FONTDIR"/ 2>/dev/null || true
  command -v fc-cache >/dev/null && fc-cache -f "$FONTDIR" >/dev/null 2>&1 || true
  say "fonts -> $FONTDIR"
fi

# ------------------------------------------------------------- launcher
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Mess Ledger launcher (generated by install.sh)
APPDIR="$APPDIR"
export PYTHONPATH="\$APPDIR:\${PYTHONPATH:-}"
case "\$1" in
  gui)       exec python3 "\$APPDIR/meal_gui.py" ;;
  phone)     exec python3 "\$APPDIR/meal_web.py" "\${2:-8137}" ;;
  tray)      exec python3 "\$APPDIR/meal_app.py" tray ;;
  watch)     exec python3 "\$APPDIR/meal_watcher.py" ;;
  remind)    exec python3 "\$APPDIR/meal_reminder.py" ;;
  analytics) exec python3 "\$APPDIR/meal_app.py" analytics ;;
  backup)    exec python3 "\$APPDIR/meal_app.py" backup ;;
  *)         exec python3 "\$APPDIR/meal_gui.py" ;;
esac
EOF
chmod +x "$LAUNCHER"
say "launcher -> $LAUNCHER"

# -------------------------------------------------------------- desktop
DESKTOP_EXEC="$LAUNCHER"
cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Name=Mess Ledger
GenericName=Meal journal
Comment=Track breakfast, lunch and dinner in a paper journal
Exec=$DESKTOP_EXEC gui
Icon=food-journal
Terminal=false
Categories=Utility;Education;
StartupNotify=true
StartupWMClass=FoodJournal
EOF
chmod +x "$DESKTOP_FILE"
command -v update-desktop-database >/dev/null && \
  update-desktop-database "$DESKTOP_DIR" >/dev/null 2>&1 || true
say "menu entry -> $DESKTOP_FILE"

# Opt-in only. Opening a journal window on every login was never asked
# for, so it stays off unless someone passes --autostart.
if [ "$AUTOSTART" = 1 ]; then
  cat > "$AUTOSTART_DIR/mess-ledger.desktop" 2>/dev/null <<EOF
[Desktop Entry]
Type=Application
Name=Mess Ledger
Exec=$DESKTOP_EXEC gui
Icon=food-journal
X-GNOME-Autostart-enabled=true
EOF
  say "will start with your session (--no-autostart to undo)"
else
  rm -f "$AUTOSTART_DIR/mess-ledger.desktop"
  say "does not start with your session (use --autostart to change this)"
fi

case ":$PATH:" in
  *":$BINDIR:"*) ;;
  *) say ""
     say "  add this to your PATH to run 'mess-ledger' from anywhere:"
     say "    echo 'export PATH=\"$BINDIR:\$PATH\"' >> ~/.bashrc"
     say "" ;;
esac

printf '\nInstalled.\n\n'
say "run it now:      $LAUNCHER"
say "phone on Wi-Fi:  $LAUNCHER phone"
say "remove later:    ./install.sh --uninstall"
printf '\n'

[ "$LAUNCH" = 1 ] && exec "$LAUNCHER" gui